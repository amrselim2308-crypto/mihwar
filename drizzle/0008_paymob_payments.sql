CREATE TABLE `payment_attempts` (
  `id` int NOT NULL AUTO_INCREMENT,
  `bookingRequestId` int NOT NULL,
  `parentUserId` int NOT NULL,
  `teacherUserId` int NOT NULL,
  `provider` varchar(32) NOT NULL DEFAULT 'paymob',
  `currency` varchar(3) NOT NULL,
  `amountMinor` int NOT NULL,
  `platformAmountMinor` int NOT NULL,
  `teacherAmountMinor` int NOT NULL,
  `commissionBps` int NOT NULL DEFAULT 3000,
  `status` enum('created','pending_provider','captured','failed','cancelled','expired','requires_review') NOT NULL DEFAULT 'created',
  `idempotencyKey` varchar(80) NOT NULL,
  `activeBookingId` int DEFAULT NULL,
  `specialReference` varchar(120) NOT NULL,
  `paymobIntentionId` varchar(120) DEFAULT NULL,
  `paymobOrderId` varchar(80) DEFAULT NULL,
  `clientSecret` varchar(1024) DEFAULT NULL,
  `checkoutUrl` varchar(2048) DEFAULT NULL,
  `paymobTransactionId` varchar(80) DEFAULT NULL,
  `providerPayloadHash` varchar(64) DEFAULT NULL,
  `expiresAt` timestamp NULL DEFAULT NULL,
  `capturedAt` timestamp NULL DEFAULT NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `payment_attempts_idempotencyKey_unique` (`idempotencyKey`),
  UNIQUE KEY `payment_attempts_activeBookingId_unique` (`activeBookingId`),
  UNIQUE KEY `payment_attempts_specialReference_unique` (`specialReference`),
  UNIQUE KEY `payment_attempts_paymobOrderId_unique` (`paymobOrderId`),
  UNIQUE KEY `payment_attempts_paymobTransactionId_unique` (`paymobTransactionId`),
  KEY `payment_attempts_booking_idx` (`bookingRequestId`),
  KEY `payment_attempts_parent_idx` (`parentUserId`),
  KEY `payment_attempts_status_idx` (`status`)
) ENGINE=InnoDB;

CREATE TABLE `provider_webhook_events` (
  `id` int NOT NULL AUTO_INCREMENT,
  `provider` varchar(32) NOT NULL,
  `providerEventId` varchar(120) NOT NULL,
  `paymentAttemptId` int DEFAULT NULL,
  `signatureValid` boolean NOT NULL,
  `payloadHash` varchar(64) NOT NULL,
  `processingStatus` enum('received','processed','duplicate','rejected','needs_review') NOT NULL DEFAULT 'received',
  `receivedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `processedAt` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `provider_webhook_event_unique` (`provider`,`providerEventId`),
  KEY `provider_webhook_payment_idx` (`paymentAttemptId`)
) ENGINE=InnoDB;

CREATE TABLE `financial_ledger_entries` (
  `id` int NOT NULL AUTO_INCREMENT,
  `paymentAttemptId` int NOT NULL,
  `sourceReference` varchar(160) NOT NULL,
  `accountCode` varchar(48) NOT NULL,
  `entrySide` enum('debit','credit') NOT NULL,
  `amountMinor` int NOT NULL,
  `currency` varchar(3) NOT NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `financial_ledger_source_account_unique` (`sourceReference`,`accountCode`),
  KEY `financial_ledger_payment_idx` (`paymentAttemptId`)
) ENGINE=InnoDB;
